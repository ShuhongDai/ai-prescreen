// Writes worker/src/generated/dashboard.ts: the dashboard's page, stylesheet and script
// (worker/dashboard/; the script's TypeScript types stripped by Node) as strings the Worker
// serves. Run by wrangler before each build (worker/wrangler.toml, [build]) and before
// `npm test`; not committed.
//   node scripts/worker-dashboard.ts

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'worker', 'dashboard');
const out = join(root, 'worker', 'src', 'generated', 'dashboard.ts');
const read = (name: string) => readFileSync(join(dir, name), 'utf8');

const source =
  '// Generated by scripts/worker-dashboard.ts from worker/dashboard/. Do not edit.\n' +
  `export const DASHBOARD_HTML = ${JSON.stringify(read('index.html'))};\n` +
  `export const DASHBOARD_CSS = ${JSON.stringify(read('dashboard.css'))};\n` +
  `export const DASHBOARD_JS = ${JSON.stringify(stripTypeScriptTypes(read('client.ts')))};\n`;
// Unchanged: leave the file alone, so `wrangler dev` does not rebuild for nothing.
const unchanged = existsSync(out) && readFileSync(out, 'utf8') === source;
if (!unchanged) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, source);
}
console.log(`worker-dashboard: → ${out.slice(root.length + 1)}${unchanged ? ' (unchanged)' : ''}`);
