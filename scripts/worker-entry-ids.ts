// Writes worker/src/generated/entry-ids.ts: every lexicon entry ID, so that the Worker counts
// hits and accepts false-positive reports only for entries that exist. Run by wrangler before
// each build (worker/wrangler.toml, [build]) and before `npm test`; not committed.
//   node scripts/worker-entry-ids.ts

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lexiconDir = join(root, 'lexicon');
const out = join(root, 'worker', 'src', 'generated', 'entry-ids.ts');

const ids = readdirSync(lexiconDir)
  .filter((f) => f.endsWith('.json'))
  .flatMap((f) => (JSON.parse(readFileSync(join(lexiconDir, f), 'utf8')) as { id: string }[]).map((e) => e.id))
  .sort();

const source =
  '// Generated by scripts/worker-entry-ids.ts from lexicon/*.json. Do not edit.\n' +
  `export const ENTRY_IDS: readonly string[] = ${JSON.stringify(ids)};\n`;
// Unchanged: leave the file alone, so `wrangler dev` does not rebuild for nothing.
const unchanged = existsSync(out) && readFileSync(out, 'utf8') === source;
if (!unchanged) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, source);
}
console.log(`worker-entry-ids: ${ids.length} IDs → ${out.slice(root.length + 1)}${unchanged ? ' (unchanged)' : ''}`);
