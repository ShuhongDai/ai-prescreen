// Inflection for lexicon entries with "inflect": true. Pure functions, no DOM.
//
// Every content token of a pattern gets its verb forms (-s, -ed, -ing), noun plural and
// British/American spelling variants. The rules over-generate on purpose: a form that is
// not an English word ("crucialing") never occurs in text, so it costs nothing. What the
// rules try hard to avoid is producing a DIFFERENT common word (hop -> "hoped", scar ->
// "scared", lead -> "leaded"), because that would be a false positive.
//
// Lexicon authors: set "inflect" on verbs and nouns. On adjectives it only adds harmless
// non-words, except where a plural is a word of its own ("vital" -> "vitals").

