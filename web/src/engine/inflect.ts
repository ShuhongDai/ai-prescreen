const PLAIN_WORD = /^[a-z]+(?:-[a-z]+)*$/;
// One vowel between a consonant (or the word start) and a final consonant that may
// double (not w, x or y): "hop", "spur", "underpin".
const CVC = /(?:^|[^aeiou])[aeiou][bcdfghjklmnpqrstvz]$/;
const VOWEL_CONSONANT = /[aeiou][bcdfghjklmnpqrstvz]$/;
const VOWEL_GROUP = /[aeiouy]+/g;
// -ise/-ize and -yse/-yze verbs, and -isation/-ization nouns (with their own inflections).
const IZE_VERB = /^(.{3,}?)([iy])[sz]e$/;
const IZE_FORM = /^(.{3,}?)([iy])[sz](es|ed|ing|ation|ations)$/;
// Latin and Greek nouns whose -ion is never pluralised with -a (nation, decision, ...).
const ION_NOUN = /(?:t|s|c|x)ion$/;

/**
 * Stems that "-ed" / "-ing" attach to, for a word that does not end in "e" or
 * consonant + "y". A final consonant after a vowel may double; stress is unknown, so
 * both spellings are generated (underpin -> underpinned, target -> targeted, equip ->
 * equipped, fuel -> fuelled / fueled). Only one-syllable words with a single vowel
 * always double (hop -> hopped), which also keeps "hoped" and "scared" out.
 */
function consonantStems(w: string): string[] {
  const last = w[w.length - 1]!;
  if (/[aeiou]c$/.test(w)) return [w, w + 'k']; // panic -> panicked
  if (!VOWEL_CONSONANT.test(w)) return [w];
  const syllables = w.match(VOWEL_GROUP)?.length ?? 0;
  return syllables <= 1 && CVC.test(w) ? [w + last] : [w, w + last];
}

/** Regular forms of a lower-case word without hyphens. */
function regularForms(w: string, out: Set<string>): void {
  // -s: third person singular and noun plural.
  if (/(?:s|x|z|ch|sh)$/.test(w)) out.add(w + 'es');
  else if (/[^aeiou]y$/.test(w)) out.add(w.slice(0, -1) + 'ies');
  else if (/[^aeiou]o$/.test(w)) out.add(w + 's').add(w + 'es');
  else out.add(w + 's');
  // Latin and Greek plurals: analysis -> analyses, spectrum -> spectra,
  // criterion -> criteria (the regular plural is kept as well).
  if (w.length >= 4 && w.endsWith('is')) out.add(w.slice(0, -2) + 'es');
  if (w.length >= 5 && w.endsWith('um')) out.add(w.slice(0, -2) + 'a');
  if (w.length >= 8 && w.endsWith('on') && !ION_NOUN.test(w)) out.add(w.slice(0, -2) + 'a');

  // -ed
  const irregular = IRREGULAR_PAST.get(w);
  if (irregular) for (const f of irregular) out.add(f);
  else if (w.endsWith('e')) out.add(w + 'd');
  else if (/[^aeiou]y$/.test(w)) out.add(w.slice(0, -1) + 'ied');
  else for (const stem of consonantStems(w)) out.add(stem + 'ed');

  // -ing
  if (w.endsWith('ie')) out.add(w.slice(0, -2) + 'ying');
  else if (/(?:ee|ye|oe)$/.test(w)) out.add(w + 'ing');
  else if (w.endsWith('e')) out.add(w.slice(0, -1) + 'ing');
  else for (const stem of consonantStems(w)) out.add(stem + 'ing');
}

/** Forms of one spelling of a lower-case word without hyphens, added to `out`. */
function addForms(w: string, out: Set<string>): void {
  out.add(w);
  const verb = w.length >= 6 ? IZE_VERB.exec(w) : null;
  if (verb) {
    // utilize / utilise: both spellings of every form, plus the -ization noun.
    const stem = verb[1]!;
    const v = verb[2]!;
    for (const z of ['z', 's']) {
      const base = stem + v + z;
      out.add(base + 'e').add(base + 'ed').add(base + 'ing');
      // "analyses" is the plural of "analysis", so the -yse verb gets no "-yses" form.
      if (v === 'i' || z === 'z') out.add(base + 'es');
      if (v === 'i') out.add(base + 'ation').add(base + 'ations');
    }
    return;
  }
  if (/i[sz]ations?$/.test(w)) {
    // optimization / optimisation (and plurals).
    const stem = w.replace(/i[sz]ations?$/, '');
    for (const z of ['z', 's']) out.add(`${stem}i${z}ation`).add(`${stem}i${z}ations`);
    return;
  }
  const form = IZE_FORM.exec(w);
  if (form) {
    // A pattern written with an inflected -ize/-ise form: add the other spelling.
    const stem = form[1]!;
    const v = form[2]!;
    const suffix = form[3]!;
    if (!(v === 'y' && suffix === 'es')) for (const z of ['z', 's']) out.add(stem + v + z + suffix);
    return;
  }
  regularForms(w, out);
}

/**
 * British and American spellings of -or / -our words (endeavor / endeavour,
 * behavior / behaviour). Short -our words are left alone (four, hour, pour, tour), and
 * so are -oor words (door, floor, poor).
 */
function spellings(w: string): string[] {
  if (w.length >= 6 && w.endsWith('our')) return [w, w.slice(0, -3) + 'or'];
  if (w.length >= 4 && /[^o]or$/.test(w)) return [w, w.slice(0, -2) + 'our'];
  return [w];
}

/** All forms of a lower-case word without hyphens (including the word itself). */
function wordForms(w: string): Set<string> {
  const out = new Set<string>([w]);
  for (const spelling of spellings(w)) addForms(spelling, out);
  return out;
}

/**
 * Forms of one pattern token for an entry with "inflect": true. The token itself comes
 * first (unchanged), followed by generated lower-case forms: verb forms (-s/-es/-ies,
 * -ed/-d/-ied, -ing), irregular pasts from a table, noun plurals (including
 * analysis/analyses, spectrum/spectra, criterion/criteria), and British/American
 * variants (-ize/-ise, -yze/-yse, -ization/-isation, -or/-our). In a hyphenated token
 * only the last part is inflected ("fine-tune" -> "fine-tuned").
 *
 * Nouns that are also verbs get the verb forms too (landscape -> "landscaping"); the
 * lexicon schema has no part of speech, so that over-generation is a known limitation.
 *
 * Function words, words shorter than three letters (unless listed as irregular verbs,
 * like "go") and tokens that are not plain ASCII words (digits, apostrophes,
 * punctuation) are returned unchanged.
 */
export function inflectWord(token: string): string[] {
  const lower = token.toLowerCase();
  if (!PLAIN_WORD.test(lower)) return [token];
  const dash = lower.lastIndexOf('-');
  const prefix = lower.slice(0, dash + 1);
  const word = lower.slice(dash + 1);
  if ((word.length < 3 && !IRREGULAR_PAST.has(word)) || FUNCTION_WORDS.has(word)) return [token];
  const forms = [token];
  for (const f of wordForms(word)) {
    const full = prefix + f;
    if (full !== lower) forms.push(full);
  }
  return forms;
}

/**
 * Forms of every whitespace-separated token of a pattern (see inflectWord). The engine
 * matches a phrase when each token matches one of its forms: "delve into" matches
 * "delving into" and "delved   into".
 */
export function inflectPattern(pattern: string): string[][] {
  const p = normalize(pattern).trim();
  return p === '' ? [] : p.split(/\s+/).map(inflectWord);
}
